; Задание 1. Поиск максимума в массиве (целые числа без знака, 16 бит)
; Первый элемент массива - количество элементов N.
; Результат записывается в ячейку MAX памяти данных.

.data 0
ARR:    .word 10, 1200, 45, 65000, 7, 3000, 64999, 0, 512, 40000, 99
MAX:    .word 0

.code
        MOV  R1, ARR        ; R1 <- адрес массива        (непосредственная)
        MOV  R2, [R1]       ; R2 <- N                    (косвенно-регистровая)
        ADD  R1, R1, 1      ; R1 -> A[1]
        MOV  R3, [R1]       ; R3 <- max = A[1]
        SUB  R2, R2, 1      ; осталось сравнить N-1 элементов
        JZ   DONE           ; массив из одного элемента
LOOP:   ADD  R1, R1, 1      ; R1 -> A[i]
        MOV  R4, [R1]       ; R4 <- A[i]
        CMP  R3, R4         ; max - A[i]:  CF=1, если max < A[i]
        JNC  SKIP           ; max >= A[i] -> пропустить
        MOV  R3, R4         ; max <- A[i]                (регистровая)
SKIP:   SUB  R2, R2, 1      ; счетчик цикла
        JNZ  LOOP
DONE:   MOV  [MAX], R3      ; MAX <- max                 (прямая)
        HLT
