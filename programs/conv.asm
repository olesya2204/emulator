; Задание 2. Свертка двух массивов по 6 элементов, целые числа без знака:
;     S = A1*B1 + A2*B2 + ... + A6*B6
; Элементы 16-битные, произведение 32-битное, сумма хранится в 48 битах
; (три слова S2:S1:S0) - используется длинная арифметика (MUL/MULH, ADD/ADC).

.data 0
A:      .word 6, 50000, 40000, 65535, 1234, 30000, 7
B:      .word 6, 60000, 3, 65535, 20000, 45000, 9
S:      .word 0, 0, 0       ; S[0] - младшее слово, S[2] - старшее

.code
        MOV  R1, A          ; R1 -> массив A
        MOV  R2, B          ; R2 -> массив B
        MOV  R3, [R1]       ; R3 <- N (счетчик цикла)
        MOV  R5, 0          ; S0 = 0
        MOV  R6, 0          ; S1 = 0
        MOV  R7, 0          ; S2 = 0
        CMP  R3, 0
        JZ   DONE           ; пустые массивы
LOOP:   ADD  R1, R1, 1      ; R1 -> A[i]
        ADD  R2, R2, 1      ; R2 -> B[i]
        MOV  R8, [R1]       ; R8 <- A[i]
        MOV  R9, [R2]       ; R9 <- B[i]
        MUL  R10, R8, R9    ; R10 <- младшие 16 бит A[i]*B[i]
        MULH R11, R8, R9    ; R11 <- старшие 16 бит A[i]*B[i]
        ADD  R5, R5, R10    ; S0 += low,         CF - перенос
        ADC  R6, R6, R11    ; S1 += high + CF
        ADC  R7, R7, 0      ; S2 += CF
        SUB  R3, R3, 1
        JNZ  LOOP
DONE:   MOV  [S], R5        ; запись 48-битного результата в ОЗУ
        MOV  [S+1], R6
        MOV  [S+2], R7
        HLT
